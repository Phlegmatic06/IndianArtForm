let currentArtifactIndex = 0;

document.addEventListener('DOMContentLoaded', () => {
    initHeroImage();
    initTimeline();
    initSourcesTable();
    setupEventListeners();
});

function initHeroImage() {
    const heroImg = document.getElementById('hero-img');
    if (heroImg) {
        heroImg.onerror = () => {
            const container = document.getElementById('hero-image-container');
            container.innerHTML = `
                <div class="hero-placeholder">
                    <div class="hero-placeholder-top">
                        OBJECT / IMAGE STUDY<br>VISUAL INDIA ARCHIVE
                    </div>
                    <div class="hero-placeholder-bottom">
                        01&mdash;08
                    </div>
                </div>
            `;
        };
    }
}

function initTimeline() {
    const container = document.getElementById('timeline-container');
    
    // Era marker definitions
    const eraMarkers = {
        0: "INDUS VALLEY<br>c. 2600–1900 BCE",
        2: "AJANTA<br>5th century CE",
        4: "CHOLA<br>11th century CE",
        5: "MUGHAL<br>early 17th century CE",
        6: "MADHUBANI / MITHILA<br>Living Tradition",
        7: "WARLI<br>Living Tradition"
    };
    
    artifacts.forEach((artifact, index) => {
        // Inject era marker if defined for this index
        if (eraMarkers[index]) {
            const eraDiv = document.createElement('div');
            eraDiv.className = 'timeline-era';
            eraDiv.innerHTML = `<span class="timeline-era-text">${eraMarkers[index]}</span>`;
            container.appendChild(eraDiv);
        }
        
        const item = document.createElement('div');
        item.className = `timeline-item tradition-${artifact.traditionClass}`;
        
        // Setup image container with fallback handling
        const visualHtml = `
            <div class="item-visual" data-index="${index}" tabindex="0" role="button" aria-label="Explore ${artifact.title}">
                <div class="image-wrapper" id="thumb-wrapper-${index}">
                    <img src="${artifact.image}" alt="${artifact.title}" id="thumb-img-${index}">
                </div>
            </div>
        `;
        
        item.innerHTML = `
            <div class="item-marker"></div>
            ${visualHtml}
            <div class="item-content">
                <div class="item-period">${artifact.purposeLabel}</div>
                <div class="item-date">${artifact.date}</div>
                <h3 class="item-title">${artifact.title}</h3>
                <button class="explore-btn" data-index="${index}">Explore Artifact</button>
            </div>
        `;
        
        container.appendChild(item);

        // Fallback for missing images
        const img = item.querySelector(`#thumb-img-${index}`);
        img.onerror = () => {
            const wrapper = item.querySelector(`#thumb-wrapper-${index}`);
            wrapper.innerHTML = `
                <div class="placeholder">
                    <span class="placeholder-title">${artifact.title}</span>
                    <span class="placeholder-text">Image source to be added</span>
                </div>
            `;
        };
    });
}

function initSourcesTable() {
    const tbody = document.getElementById('sources-tbody');
    
    artifacts.forEach(artifact => {
        const row = document.createElement('tr');
        
        // Build image source HTML
        let sourceHtml = artifact.imageSource || 'To be added';
        if (artifact.imageSourceLink) {
            sourceHtml = `<a href="${artifact.imageSourceLink}" target="_blank" rel="noopener noreferrer">${artifact.imageSource}</a>`;
        }
        
        row.innerHTML = `
            <td>${artifact.title}</td>
            <td>${artifact.researchInstitution ? artifact.researchInstitution.replace(/\n/g, '<br>') : ''}</td>
            <td>${sourceHtml}</td>
            <td>${artifact.imageLicense || 'To be verified'}</td>
        `;
        tbody.appendChild(row);
    });
}

function setupEventListeners() {
    // Scroll to timeline
    document.getElementById('begin-journey').addEventListener('click', () => {
        document.getElementById('timeline').scrollIntoView({ behavior: 'smooth' });
    });

    // Open detail view
    document.getElementById('timeline-container').addEventListener('click', (e) => {
        const visual = e.target.closest('.item-visual');
        const btn = e.target.closest('.explore-btn');
        const title = e.target.closest('.item-title');
        
        if (visual) {
            openDetailView(parseInt(visual.getAttribute('data-index')));
        } else if (btn) {
            openDetailView(parseInt(btn.getAttribute('data-index')));
        } else if (title) {
            const indexBtn = title.closest('.item-content').querySelector('.explore-btn');
            if (indexBtn) openDetailView(parseInt(indexBtn.getAttribute('data-index')));
        }
    });

    document.getElementById('timeline-container').addEventListener('keydown', (e) => {
        if (e.key === 'Enter' || e.key === ' ') {
            const visual = e.target.closest('.item-visual');
            if (visual) {
                e.preventDefault();
                openDetailView(parseInt(visual.getAttribute('data-index')));
            }
        }
    });

    // Close detail view
    document.querySelector('#detail-modal .close-btn').addEventListener('click', closeDetailView);
    document.querySelector('#detail-modal .modal-backdrop').addEventListener('click', closeDetailView);

    // Zoom image
    document.getElementById('detail-image-container').addEventListener('click', openZoomView);
    
    // Close zoom view
    document.querySelector('.zoom-close-btn').addEventListener('click', closeZoomView);
    document.querySelector('.zoom-backdrop').addEventListener('click', closeZoomView);

    // Navigation
    document.getElementById('prev-artifact').addEventListener('click', () => navigateArtifact(-1));
    document.getElementById('next-artifact').addEventListener('click', () => navigateArtifact(1));

    // Keyboard navigation
    document.addEventListener('keydown', (e) => {
        const detailModal = document.getElementById('detail-modal');
        const zoomModal = document.getElementById('zoom-modal');
        
        if (zoomModal.classList.contains('active')) {
            if (e.key === 'Escape') closeZoomView();
        } else if (detailModal.classList.contains('active')) {
            if (e.key === 'Escape') closeDetailView();
            if (e.key === 'ArrowLeft') navigateArtifact(-1);
            if (e.key === 'ArrowRight') navigateArtifact(1);
        }
    });
}

function openDetailView(index) {
    currentArtifactIndex = index;
    const artifact = artifacts[index];
    
    // Update content
    const topLabel = document.getElementById('detail-top-label');
    topLabel.textContent = `ARTIFACT 0${index + 1} / 0${artifacts.length}`;
    
    document.getElementById('detail-title').textContent = artifact.title;
    
    const artistEl = document.getElementById('detail-artist');
    if (artifact.artist && artifact.artist !== "Unknown") {
        artistEl.textContent = artifact.artist;
        artistEl.style.display = 'block';
    } else {
        artistEl.style.display = 'none';
    }
    
    document.getElementById('detail-tradition').textContent = artifact.tradition;
    document.getElementById('detail-date').textContent = artifact.date;
    
    updateMetaRow('location', artifact.location);
    updateMetaRow('material', artifact.material);
    updateMetaRow('dimensions', artifact.dimensions);
    updateMetaRow('collection', artifact.collection);
    
    document.getElementById('detail-description').textContent = artifact.description;
    document.getElementById('detail-lookcloser').textContent = artifact.lookCloser;
    document.getElementById('detail-identity').textContent = artifact.identity;
    document.getElementById('detail-purpose').textContent = artifact.purpose;
    document.getElementById('detail-credit').textContent = artifact.imageCredit;
    
    // Update image
    const imgContainer = document.getElementById('detail-image-container');
    const imgElement = document.createElement('img');
    imgElement.src = artifact.image;
    imgElement.alt = artifact.title;
    imgElement.id = 'detail-img-element';
    
    imgContainer.innerHTML = '';
    imgContainer.appendChild(imgElement);
    
    imgElement.onerror = () => {
        imgContainer.innerHTML = `
            <div class="placeholder" style="width: 100%; height: 50vh;">
                <span class="placeholder-title" style="font-size: 1.5rem; margin-bottom: 1rem;">${artifact.title}</span>
                <span class="placeholder-text">Image source to be added</span>
            </div>
        `;
        imgContainer.style.cursor = 'default';
        imgContainer.onclick = null; // disable zoom if missing
    };

    imgElement.onload = () => {
        imgContainer.style.cursor = 'zoom-in';
        imgContainer.onclick = openZoomView;
    };
    
    // Update nav buttons
    document.getElementById('prev-artifact').style.visibility = index === 0 ? 'hidden' : 'visible';
    document.getElementById('next-artifact').style.visibility = index === artifacts.length - 1 ? 'hidden' : 'visible';
    
    // Show modal
    const modal = document.getElementById('detail-modal');
    modal.classList.add('active');
    document.body.style.overflow = 'hidden';
}

function updateMetaRow(id, value) {
    const row = document.getElementById(`row-${id}`);
    if (!row) return; // safeguard if row doesn't exist in HTML
    
    if (value) {
        row.style.display = 'flex';
        document.getElementById(`detail-${id}`).textContent = value;
    } else {
        row.style.display = 'none';
    }
}

function closeDetailView() {
    document.getElementById('detail-modal').classList.remove('active');
    document.body.style.overflow = 'auto';
}

function navigateArtifact(direction) {
    const newIndex = currentArtifactIndex + direction;
    if (newIndex >= 0 && newIndex < artifacts.length) {
        openDetailView(newIndex);
    }
}

function openZoomView() {
    const imgElement = document.getElementById('detail-img-element');
    if (!imgElement) return; // Don't zoom if placeholder
    
    const zoomImg = document.getElementById('zoomed-image');
    zoomImg.src = imgElement.src;
    
    document.getElementById('zoom-modal').classList.add('active');
}

function closeZoomView() {
    document.getElementById('zoom-modal').classList.remove('active');
}
